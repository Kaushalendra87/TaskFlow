from datetime import date, timedelta

from django.db.models import Count, Q
from django.utils import timezone

from rest_framework import status
from rest_framework.permissions import IsAuthenticated, IsAdminUser
from rest_framework.response import Response
from rest_framework.views import APIView

from jobs.models import Job, DailyJobSummary
from jobs.serializers import DailyJobSummarySerializer


class JobSummaryAPIView(APIView):
    """
    Return live job statistics for the authenticated user.

    GET /api/jobs/summary/
    """

    permission_classes = [IsAuthenticated]

    def get(self, request):
        # Restrict the queryset to the currently authenticated user.
        queryset = Job.objects.filter(user=request.user)

        # Calculate all statistics in a single database query.
        counts = queryset.aggregate(
            total_jobs=Count("id"),

            pending_jobs=Count(
                "id",
                filter=Q(status=Job.Status.PENDING),
            ),

            processing_jobs=Count(
                "id",
                filter=Q(status=Job.Status.PROCESSING),
            ),

            retrying_jobs=Count(
                "id",
                filter=Q(status=Job.Status.RETRYING),
            ),

            completed_jobs=Count(
                "id",
                filter=Q(status=Job.Status.COMPLETED),
            ),

            failed_jobs=Count(
                "id",
                filter=Q(status=Job.Status.FAILED),
            ),

            cancelled_jobs=Count(
                "id",
                filter=Q(status=Job.Status.CANCELLED),
            ),
        )

        return Response(
            counts,
            status=status.HTTP_200_OK,
        )


class DailyJobSummaryAPIView(APIView):
    """
    Retrieve a stored daily job summary.

    GET /api/jobs/summary/daily/
    GET /api/jobs/summary/daily/?date=YYYY-MM-DD

    Only staff users may access global daily summaries.
    """

    permission_classes = [IsAdminUser]

    def get(self, request):
        date_value = request.query_params.get("date")

        # Default to yesterday when no date is provided.
        if not date_value:
            summary_date = (
                timezone.localdate() - timedelta(days=1)
            )

        else:
            # Validate the requested date.
            try:
                summary_date = date.fromisoformat(date_value)

            except (ValueError, TypeError):
                return Response(
                    {
                        "detail": "Invalid date. Use YYYY-MM-DD.",
                        "code": "invalid_date",
                    },
                    status=status.HTTP_400_BAD_REQUEST,
                )

            # Reject alternative ISO formats such as YYYYMMDD.
            if summary_date.isoformat() != date_value:
                return Response(
                    {
                        "detail": "Invalid date. Use YYYY-MM-DD.",
                        "code": "invalid_date",
                    },
                    status=status.HTTP_400_BAD_REQUEST,
                )

        # Retrieve the summary generated by the scheduled task.
        try:
            summary = DailyJobSummary.objects.get(
                summary_date=summary_date
            )

        except DailyJobSummary.DoesNotExist:
            return Response(
                {
                    "detail": "Daily summary not found.",
                    "code": "not_found",
                    "summary_date": summary_date.isoformat(),
                },
                status=status.HTTP_404_NOT_FOUND,
            )

        # Convert the model instance into JSON-compatible data.
        serializer = DailyJobSummarySerializer(summary)

        return Response(
            serializer.data,
            status=status.HTTP_200_OK,
        )